% ==========================================================

function createBlock( ...
    ax,x,y,w,h,color,titleText,bodyText)

    %% Block rectangle

    rectangle(ax, ...
        'Position',[x y w h], ...
        'Curvature',0.08, ...
        'FaceColor',color, ...
        'EdgeColor',[0.20 0.20 0.20], ...
        'LineWidth',1.2);

    %% Title
    % Positioned close to the upper border.

    titleY = y + h - 0.20;

    text(ax, ...
        x + w/2, ...
        titleY, ...
        titleText, ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','top', ...
        'FontName','Times New Roman', ...
        'FontSize',10.5, ...
        'FontWeight','bold');

    %% Body text
    % Explicit lower position creates separation
    % between title and body.

    body = strjoin(bodyText,'\n');

    bodyY = y + h/2 - 0.20;

    text(ax, ...
        x + w/2, ...
        bodyY, ...
        body, ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontName','Times New Roman', ...
        'FontSize',9);

end


function drawArrow(ax,p1,p2)

    %% Convert axes coordinates into normalized
    % figure coordinates for annotation arrows.

    xl = xlim(ax);
    yl = ylim(ax);

    pos = ax.Position;

    x1 = pos(1) + ...
        (p1(1)-xl(1)) / ...
        (xl(2)-xl(1)) * pos(3);

    y1 = pos(2) + ...
        (p1(2)-yl(1)) / ...
        (yl(2)-yl(1)) * pos(4);

    x2 = pos(1) + ...
        (p2(1)-xl(1)) / ...
        (xl(2)-xl(1)) * pos(3);

    y2 = pos(2) + ...
        (p2(2)-yl(1)) / ...
        (yl(2)-yl(1)) * pos(4);

    annotation( ...
        ax.Parent, ...
        'arrow', ...
        [x1 x2], ...
        [y1 y2], ...
        'Color','k', ...
        'LineWidth',1.25, ...
        'HeadLength',7, ...
        'HeadWidth',7);

end